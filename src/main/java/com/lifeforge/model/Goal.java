package com.lifeforge.model;

/**
 * A selectable lifestyle goal (e.g. Lose Weight, Build Muscle).
 * Goals are stored in PostgreSQL so admins can manage them
 * without changing Java source code.
 */
public class Goal {

    private Long id;
    private String code;
    private String name;
    private String description;
    private boolean active;

    public Goal() {
    }

    public Goal(Long id, String code, String name, String description, boolean active) {
        this.id = id;
        this.code = code;
        this.name = name;
        this.description = description;
        this.active = active;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }

    @Override
    public String toString() {
        return name;
    }
}